-- The demo's tables: customers (uuid key, choices, jsonb), their orders
-- (identity key, foreign key, nullable timestamp, text array) and their API
-- tokens (a secret the admin never shows).

CREATE TABLE IF NOT EXISTS customers (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name        text NOT NULL CHECK (name <> ''),
    email       text NOT NULL UNIQUE,
    plan        text NOT NULL DEFAULT 'free' CHECK (plan IN ('free', 'pro', 'team')),
    is_active   boolean NOT NULL DEFAULT true,
    preferences jsonb NOT NULL DEFAULT '{}',
    notes       text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id uuid NOT NULL REFERENCES customers (id) ON DELETE RESTRICT,
    status      text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'shipped', 'cancelled')),
    total_cents integer NOT NULL CHECK (total_cents >= 0),
    tags        text[] NOT NULL DEFAULT '{}',
    paid        boolean NOT NULL DEFAULT false,
    shipped_at  timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS orders_customer_id ON orders (customer_id);

CREATE TABLE IF NOT EXISTS api_tokens (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id uuid NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    label       text NOT NULL,
    secret      bytea NOT NULL DEFAULT sha256(gen_random_uuid()::text::bytea),
    created_at  timestamptz NOT NULL DEFAULT now(),
    revoked_at  timestamptz
);
